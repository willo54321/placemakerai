const BODY_LIMIT = 20000
const SNIPPET_LIMIT = 400

interface InboundMail {
  id: string
  from: string
  to: string[]
  cc: string[] | null
  received_for: string[]
  message_id: string | null
  subject: string
  text: string | null
  html: string | null
  headers: Record<string, string> | null
  attachments: Array<{ filename?: string | null; content_type?: string | null; size?: number | null }>
}

function htmlToText(html: string): string {
  return html
    .replace(/<(style|script)[\s\S]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|tr|li|h[1-6])>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** Out-of-office and other machine-generated mail must not create enquiries. */
function isAutoGenerated(headers: Record<string, string> | null): boolean {
  if (!headers) return false
  const lower = Object.fromEntries(
    Object.entries(headers).map(([k, v]) => [k.toLowerCase(), String(v).toLowerCase()])
  )
  if (lower['auto-submitted'] && lower['auto-submitted'] !== 'no') return true
  if ('x-autoreply' in lower || 'x-autorespond' in lower) return true
  const precedence = lower['precedence']
  return precedence === 'bulk' || precedence === 'auto_reply' || precedence === 'junk'
}

/**
 * Addresses of everyone on the project team (any project role, plus super
 * admins). Their emails copied to the project address are the team's own
 * correspondence, and they're never logged as stakeholders on an email.
 */
async function projectTeamEmails(projectId: string): Promise<Set<string>> {
  const [access, superAdmins] = await Promise.all([
    prisma.projectAccess.findMany({ where: { projectId }, select: { user: { select: { email: true } } } }),
    prisma.user.findMany({ where: { systemRole: 'SUPER_ADMIN' }, select: { email: true } }),
  ])
  return new Set(
    [...access.map(a => a.user.email), ...superAdmins.map(u => u.email)]
      .filter((e): e is string => Boolean(e))
      .map(e => e.toLowerCase())
  )
}

async function notifyProjectAdmins(args: {
  projectId: string
  projectName: string
  kind: 'reply' | 'new'
  fromName: string | null
  fromEmail: string
  subject: string
  snippet: string
}) {
  // Super admins have implicit access to every project, so they're alerted
  // alongside the project's own admins.
  const [access, superAdmins] = await Promise.all([
    prisma.projectAccess.findMany({
      where: { projectId: args.projectId, role: 'ADMIN' },
      select: { user: { select: { email: true } } },
    }),
    prisma.user.findMany({
      where: { systemRole: 'SUPER_ADMIN' },
      select: { email: true },
    }),
  ])
  const to = Array.from(
    new Set(
      [...access.map(a => a.user.email), ...superAdmins.map(u => u.email)].filter(
        (e): e is string => Boolean(e)
      )
    )
  )
  if (to.length === 0 && process.env.CONTACT_NOTIFY_EMAIL) {
    to.push(process.env.CONTACT_NOTIFY_EMAIL)
  }
  const baseUrl = (process.env.NEXTAUTH_URL || 'https://platform.placemakerai.io').replace(/\/$/, '')
  await sendInboundEmailNotification({ ...args, to, baseUrl })
}

/**
 * Resend `email.received` webhook: routes inbound mail on the platform domain
 * into the enquiries inbox. Recipient addresses resolve by their tag —
 * `<project>+e-<threadToken>@` appends to that enquiry's thread;
 * `<project>+c-<campaignId>@` and bare `<project>@` join the thread the email
 * replies to (by In-Reply-To/References), or else start a new one: an
 * email-channel enquiry when it was sent to the project, or a 'copied' thread
 * when the project was only CC'd/BCC'd or a team member sent it from their
 * own mail client (see classifyNewThread). Unknown addresses are acknowledged
 * and dropped (a 200 stops Resend retrying; spam to guessed addresses must
 * not 500 the endpoint).
 */
export async function POST(request: Request) {
  const secret = process.env.RESEND_WEBHOOK_SECRET
  if (!secret) {
    return NextResponse.json({ error: 'Inbound email not configured' }, { status: 503 })
  }

  const payload = await request.text()
  const verified = verifySvixSignature({
    secret,
    id: request.headers.get('svix-id'),
    timestamp: request.headers.get('svix-timestamp'),
    signature: request.headers.get('svix-signature'),
    payload,
  })
  if (!verified) {
    return NextResponse.json({ error: 'Invalid signature' }, { status: 401 })
  }

  let event: { type?: string; data?: { email_id?: string; id?: string } }
  try {
    event = JSON.parse(payload)
  } catch {
    return NextResponse.json({ error: 'Invalid payload' }, { status: 400 })
  }
  if (event.type !== 'email.received') return NextResponse.json({ ok: true })

  const emailId = event.data?.email_id ?? event.data?.id
  if (!emailId) return NextResponse.json({ ok: true })

  // Webhook deliveries retry; the same inbound email must only land once.
  const [seenMessage, seenEnquiry] = await Promise.all([
    prisma.enquiryMessage.findUnique({ where: { externalId: emailId }, select: { id: true } }),
    prisma.enquiry.findUnique({ where: { externalId: emailId }, select: { id: true } }),
  ])
  if (seenMessage || seenEnquiry) return NextResponse.json({ ok: true, deduped: true })

  const domain = getSenderDomain()
  const client = getResend()
  if (!domain || !client) return NextResponse.json({ ok: true })

  const { data, error } = await client.emails.receiving.get(emailId)
  if (error || !data) {
    console.error('Inbound: failed to fetch received email', emailId, error)
    // 500 so Resend retries — the email exists, we just couldn't read it yet.
    return NextResponse.json({ error: 'Fetch failed' }, { status: 500 })
  }
  const mail = data as unknown as InboundMail

  if (isAutoGenerated(mail.headers)) {
    return NextResponse.json({ ok: true, skipped: 'auto-generated' })
  }

  const recipients = (mail.received_for?.length ? mail.received_for : mail.to) ?? []
  const parsed = recipients
    .map(address => parseInboundAddress(address, domain))
    .find(Boolean)
  if (!parsed) return NextResponse.json({ ok: true, skipped: 'no recipient on domain' })

  const sender = parseMailbox(mail.from)
  const messageId = normaliseMessageId(mail.message_id)
  const body =
    (mail.text?.trim() || (mail.html ? htmlToText(mail.html) : '') || '(no content)').slice(0, BODY_LIMIT)
  const snippet = body.slice(0, SNIPPET_LIMIT)
  const subject = mail.subject?.trim() || '(no subject)'
  const attachments = mail.attachments?.length
    ? mail.attachments.map(a => ({
        name: a.filename ?? 'attachment',
        size: a.size ?? null,
        mime: a.content_type ?? null,
      }))
    : undefined

  // The people on the email other than the sender, the team and our own
  // addresses — stakeholders among them get the email in their log too.
  const recipientsFor = (team: Set<string>) => {
    const to = externalRecipients(mail.to, domain, team, [sender.email])
    const cc = externalRecipients(mail.cc, domain, team, [sender.email, ...to.map(r => r.email)])
    return { to, cc }
  }

  const appendToThread = async (
    enquiry: { id: string; subject: string; submitterEmail: string; status: string; channel: string; project: { id: string; name: string } },
    team: Set<string>,
  ) => {
    const fromTeam = team.has(sender.email)
    const { to, cc } = recipientsFor(team)
    const message = await prisma.enquiryMessage.create({
      data: {
        enquiryId: enquiry.id,
        // A team member replying from their own mail client, with the
        // project address kept on the email, is the team's side of the thread.
        direction: fromTeam ? 'outbound' : 'inbound',
        body,
        authorName: sender.name,
        authorEmail: sender.email,
        deliveryStatus: 'delivered',
        attachments,
        externalId: emailId,
        messageId,
        to: to.map(r => r.email),
        cc: cc.map(r => r.email),
      },
    })
    // Copied correspondence already reached its real recipient, so only
    // replies on the team's own threads need attention in the inbox.
    const needsAttention = !fromTeam && enquiry.channel !== 'copied'
    if (needsAttention) {
      await prisma.enquiry.update({
        where: { id: enquiry.id },
        data: { read: false, status: enquiry.status === 'closed' ? 'open' : enquiry.status },
      })
    } else if (fromTeam && enquiry.status === 'new') {
      await prisma.enquiry.update({ where: { id: enquiry.id }, data: { status: 'open' } })
    }
    await logAudit({
      projectId: enquiry.project.id,
      action: 'enquiry.inbound',
      targetType: 'enquiry',
      targetId: enquiry.id,
      detail: { emailId, from: sender.email, fromTeam },
    })
    if (needsAttention) {
      await notifyProjectAdmins({
        projectId: enquiry.project.id,
        projectName: enquiry.project.name,
        kind: 'reply',
        fromName: sender.name,
        fromEmail: sender.email,
        subject: enquiry.subject,
        snippet,
      })
    }
    after(() => captureEmailEvents(enquiry.project.id, [messageEvent(enquiry, message)]))
    return NextResponse.json({ ok: true, threaded: enquiry.id })
  }

  const threadSelect = {
    id: true, subject: true, submitterEmail: true, status: true, channel: true,
    project: { select: { id: true, name: true } },
  } as const

  // Thread reply: tag carries the enquiry's unguessable threadToken.
  if (parsed.tag?.startsWith('e-')) {
    const enquiry = await prisma.enquiry.findUnique({
      where: { threadToken: parsed.tag.slice(2) },
      select: threadSelect,
    })
    if (!enquiry) return NextResponse.json({ ok: true, skipped: 'unknown thread' })
    return appendToThread(enquiry, await projectTeamEmails(enquiry.project.id))
  }

  // Campaign reply or mail to the bare project address.
  let project: { id: string; name: string } | null = null
  if (parsed.tag?.startsWith('c-')) {
    const campaign = await prisma.campaign.findUnique({
      where: { id: parsed.tag.slice(2) },
      select: { project: { select: { id: true, name: true } } },
    })
    project = campaign?.project ?? null
  }
  if (!project) {
    project = await prisma.project.findUnique({
      where: { emailLocalPart: parsed.localPart },
      select: { id: true, name: true },
    })
  }
  if (!project) return NextResponse.json({ ok: true, skipped: 'unknown address' })
  const team = await projectTeamEmails(project.id)

  // A reply to an email we already hold (people reply-all with the project
  // address still copied in) joins that thread.
  const refs = referencedMessageIds(mail.headers)
  if (refs.length) {
    const [repliedMessage, repliedEnquiry] = await Promise.all([
      prisma.enquiryMessage.findFirst({
        where: { messageId: { in: refs }, enquiry: { projectId: project.id } },
        orderBy: { createdAt: 'desc' },
        select: { enquiryId: true },
      }),
      prisma.enquiry.findFirst({ where: { messageId: { in: refs }, projectId: project.id }, select: { id: true } }),
    ])
    const threadId = repliedMessage?.enquiryId ?? repliedEnquiry?.id
    const enquiry = threadId
      ? await prisma.enquiry.findUnique({ where: { id: threadId }, select: threadSelect })
      : null
    if (enquiry) return appendToThread(enquiry, team)
  }

  const { to, cc } = recipientsFor(team)
  const kind = classifyNewThread({
    sender,
    senderIsTeam: team.has(sender.email),
    projectInTo: addressesProject(mail.to, domain, parsed.localPart),
    to,
    cc,
  })

  // Correspondence the project address was copied on: kept as a read, open
  // thread for the record (no admin alert — its real recipient already has
  // it), with the email itself as the first message so its sender and
  // recipients are preserved.
  if (kind.kind === 'copied') {
    const { correspondent, direction } = kind
    const projectId = project.id
    const { enquiry, message } = await prisma.$transaction(async tx => {
      const enquiry = await tx.enquiry.create({
        data: {
          projectId,
          submitterName: correspondent.name ?? correspondent.email,
          submitterEmail: correspondent.email,
          subject,
          message: body,
          channel: 'copied',
          status: 'open',
          read: true,
          messageId,
        },
      })
      const message = await tx.enquiryMessage.create({
        data: {
          enquiryId: enquiry.id,
          direction,
          body,
          authorName: sender.name,
          authorEmail: sender.email,
          deliveryStatus: 'delivered',
          attachments,
          externalId: emailId,
          messageId,
          to: to.map(r => r.email),
          cc: cc.map(r => r.email),
        },
      })
      return { enquiry, message }
    })
    await logAudit({
      projectId,
      action: 'enquiry.copied',
      targetType: 'enquiry',
      targetId: enquiry.id,
      detail: { emailId, from: sender.email, direction },
    })
    after(() => captureEmailEvents(projectId, [messageEvent(enquiry, message)]))
    return NextResponse.json({ ok: true, copied: enquiry.id })
  }

  const enquiry = await prisma.enquiry.create({
    data: {
      projectId: project.id,
      submitterName: sender.name ?? sender.email,
      submitterEmail: sender.email,
      subject,
      message: body,
      channel: 'email',
      externalId: emailId,
      messageId,
    },
  })
  await logAudit({
    projectId: project.id,
    action: 'enquiry.inbound',
    targetType: 'enquiry',
    targetId: enquiry.id,
    detail: { emailId, from: sender.email, viaCampaign: parsed.tag?.startsWith('c-') ?? false },
  })
  await notifyProjectAdmins({
    projectId: project.id,
    projectName: project.name,
    kind: 'new',
    fromName: sender.name,
    fromEmail: sender.email,
    subject,
    snippet,
  })
  const projectId = project.id
  after(() => captureEmailEvents(projectId, [submissionEvent(enquiry)]))
  return NextResponse.json({ ok: true, enquiry: enquiry.id })

}
